/**
 * Returns translation for key in active language.
 * Falls back to Hindi for Indian languages if exact string not yet defined, or English.
 */
export function getTranslation(lang: string, key: TranslationKey): string {
  const langDict = TRANSLATIONS[lang];
  if (langDict && langDict[key]) {
    return langDict[key]!;
  }
  // Try Hindi first if it's an Indian regional language
  if (lang !== 'en' && TRANSLATIONS['hi'] && TRANSLATIONS['hi'][key]) {
    return TRANSLATIONS['hi'][key]!;
  }
  // Ultimate fallback to English
  return TRANSLATIONS['en']?.[key] || key;
}
